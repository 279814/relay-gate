    owner_id INTEGER PRIMARY KEY REFERENCES request_log(id) ON DELETE CASCADE,
    metadata_version INTEGER NOT NULL DEFAULT 1 CHECK(metadata_version = 1),
    execution_id TEXT NOT NULL DEFAULT '' CHECK(length(execution_id) <= 64),
    attempt INTEGER NOT NULL DEFAULT 0 CHECK(attempt >= 0),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts >= 0),
    config_generation INTEGER NOT NULL DEFAULT 0 CHECK(config_generation >= 0),
    settings_revision INTEGER NOT NULL DEFAULT 0 CHECK(settings_revision >= 0),
    endpoint_id INTEGER NOT NULL DEFAULT 0 CHECK(endpoint_id >= 0),
    endpoint_revision INTEGER NOT NULL DEFAULT 0 CHECK(endpoint_revision >= 0),
    auth_profile_revision INTEGER NOT NULL DEFAULT 0 CHECK(auth_profile_revision >= 0),
    upstream_network_revision INTEGER NOT NULL DEFAULT 0 CHECK(upstream_network_revision >= 0),
    upstream_credential_revision INTEGER NOT NULL DEFAULT 0 CHECK(upstream_credential_revision >= 0),
    route_revision INTEGER NOT NULL DEFAULT 0 CHECK(route_revision >= 0),
    route_capability_revision INTEGER NOT NULL DEFAULT 0 CHECK(route_capability_revision >= 0),
    model_revision INTEGER NOT NULL DEFAULT 0 CHECK(model_revision >= 0),
    model_capability_revision INTEGER NOT NULL DEFAULT 0 CHECK(model_capability_revision >= 0),
    transform_version_id INTEGER NOT NULL DEFAULT 0 CHECK(transform_version_id >= 0),
    request_transform_revision INTEGER NOT NULL DEFAULT 0 CHECK(request_transform_revision >= 0),
    response_header_at_ms INTEGER NOT NULL DEFAULT 0 CHECK(response_header_at_ms >= 0),
    first_event_at_ms INTEGER NOT NULL DEFAULT 0 CHECK(first_event_at_ms >= 0),
    first_semantic_at_ms INTEGER NOT NULL DEFAULT 0 CHECK(first_semantic_at_ms >= 0),
    retry_policy TEXT NOT NULL DEFAULT 'unknown' CHECK(retry_policy IN ('unknown','safe','balanced','aggressive')),
    retry_reason TEXT NOT NULL DEFAULT '' CHECK(length(retry_reason) <= 96),
    request_write_state TEXT NOT NULL DEFAULT 'unknown' CHECK(request_write_state IN ('unknown','not_written','possibly_written','written')),
    capability_effect TEXT NOT NULL DEFAULT 'unknown' CHECK(capability_effect IN ('unknown','pending','unavailable','dropped','applied','config_stale','superseded','not_applicable','ignored')),
    error_class TEXT NOT NULL DEFAULT 'unknown' CHECK(error_class IN ('unknown','none','unreachable','auth_rejected','request_shape_rejected','config_error','unsupported','model_not_found','rate_limited','transient_error','fake_alive','partial_failure','ignored')),
    retried INTEGER NOT NULL DEFAULT 0 CHECK(retried IN (0,1)),
    half_open INTEGER NOT NULL DEFAULT 0 CHECK(half_open IN (0,1)),
    duplicate_risk INTEGER NOT NULL DEFAULT 0 CHECK(duplicate_risk IN (0,1)),
    synthetic_completion INTEGER NOT NULL DEFAULT 0 CHECK(synthetic_completion IN (0,1)),
    request_input_hash TEXT NOT NULL DEFAULT '' CHECK(length(request_input_hash) IN (0,64)),
    request_output_hash TEXT NOT NULL DEFAULT '' CHECK(length(request_output_hash) IN (0,64)),
    request_body_changed INTEGER NOT NULL DEFAULT 0 CHECK(request_body_changed IN (0,1)),
    request_headers_changed INTEGER NOT NULL DEFAULT 0 CHECK(request_headers_changed IN (0,1)),
    request_diff_reason TEXT NOT NULL DEFAULT 'unknown' CHECK(request_diff_reason IN ('unknown','recorded','secret_taint','incomplete','sample_disabled')),
    response_input_hash TEXT NOT NULL DEFAULT '' CHECK(length(response_input_hash) IN (0,64)),
    response_output_hash TEXT NOT NULL DEFAULT '' CHECK(length(response_output_hash) IN (0,64)),
    response_body_changed INTEGER NOT NULL DEFAULT 0 CHECK(response_body_changed IN (0,1)),
    response_headers_changed INTEGER NOT NULL DEFAULT 0 CHECK(response_headers_changed IN (0,1)),
    response_diff_reason TEXT NOT NULL DEFAULT 'unknown' CHECK(response_diff_reason IN ('unknown','recorded','secret_taint','incomplete','sample_disabled'))
);
CREATE INDEX idx_request_log_metadata_execution ON request_log_metadata(execution_id);

