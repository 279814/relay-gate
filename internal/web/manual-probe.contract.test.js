const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
eval(fs.readFileSync(path.join(__dirname, 'static/app.js'), 'utf8'));

(async () => {
  const shell = app();
  let requests = 0;
  shell.api = async (method, resource) => {
    assert.equal(method, 'POST'); assert.equal(resource, '/routes/7/probe'); requests++;
    return {execution_id: 'one-execution', ok: false, execution: {RouteID: 7, Endpoint: 'messages', StatusCode: 200,
      Success: false, ErrorClass: 'partial_failure', Capability: 'transient_error', Reachable: true,
      SemanticSeen: true, NormalEndSeen: false, SentAtMS: 1000, FirstSemanticAtMS: 1012, DoneAtMS: 1040,
      RedactedDetail: 'upstream_closed'}};
  };
  shell.loadHealth = async () => {};
  await shell.probe(7);
  assert.equal(requests, 1, 'manual action sends one model attempt');
  const result = shell.manualProbeResult();
  assert.equal(result.routeId, 7); assert.equal(result.endpoint, 'messages');
  assert.equal(result.success, false); assert.equal(result.errorClass, 'partial_failure');
  assert.equal(result.semanticMS, '12ms'); assert.equal(result.totalMS, '40ms');
  assert.equal(result.normalEndSeen, false);
  shell.probeResult = {execution: {route_id: 8, endpoint: 'responses', sent_at_ms: 0, first_semantic_at_ms: 0, done_at_ms: 3}};
  assert.equal(shell.manualProbeResult().semanticMS, '—', 'unsent execution must not invent timing');
  assert.equal(shell.manualProbeResult().totalMS, '—');
  shell.probeResult = {l1: {verdict: 'ok'}, l2: {verdict: 'ok'}};
  assert.equal(shell.manualProbeResult(), null, 'retired Outcome pair is not an execution');
  const page = fs.readFileSync(path.join(__dirname, 'static/index.html'), 'utf8');
  assert.doesNotMatch(page, /probeResult\.(l1|l2|route_id)/);
  assert.match(page, /hdrExport\.candidate/);
  assert.doesNotMatch(page, /建议的 probe_headers|填入该上游的表单/);

  const sampleShell = app(); sampleShell.authed = true;
  const calls = [];
  sampleShell.api = async (...args) => {calls.push(args); throw Object.assign(new Error('管理员口令不正确'), {status: 403});};
  sampleShell.openSample(44);
  assert.equal(calls.length, 0, 'view must wait for explicit reauthentication');
  assert.equal(sampleShell.sampleAccess.kind, 'view');
  sampleShell.samplePassword = 'wrong-password';
  await sampleShell.confirmSampleAccess();
  assert.deepEqual(calls[0], ['POST', '/samples/44/view', {password: 'wrong-password'}]);
  assert.equal(sampleShell.authed, true, 'wrong reauth must not destroy a valid session');
  assert.equal(sampleShell.sample, null);
  assert.equal(sampleShell.samplePassword, '', 'password must clear after a failed request');
  assert.ok(sampleShell.sampleAccess, 'failure keeps a usable retry dialog');
  sampleShell.api = async (...args) => {calls.push(args); return {id: 44, in_body: 'authorized-body'};};
  sampleShell.samplePassword = 'correct-password';
  await sampleShell.confirmSampleAccess();
  assert.equal(sampleShell.sample.id, 44);
  assert.equal(sampleShell.sampleAccess, null);
  assert.equal(sampleShell.samplePassword, '');
  const row = {id: 44, pinned: false};
  sampleShell.togglePin(row);
  sampleShell.samplePassword = 'correct-password';
  sampleShell.api = async (...args) => {calls.push(args); return {id: 44, pinned: true};};
  await sampleShell.confirmSampleAccess();
  assert.deepEqual(calls.at(-1), ['POST', '/samples/44/pin', {pinned: true, password: 'correct-password'}]);
  assert.equal(row.pinned, true);
  sampleShell.openSample(44); sampleShell.samplePassword = 'never-submit';
  sampleShell.closeSampleAccess();
  assert.equal(sampleShell.samplePassword, ''); assert.equal(sampleShell.sampleAccess, null);
  sampleShell.openSample(44); sampleShell.samplePassword = 'logout-must-clear';
  sampleShell.reset();
  assert.equal(sampleShell.samplePassword, ''); assert.equal(sampleShell.sampleAccess, null);
  const countBeforeInvalidAction = calls.length;
  sampleShell.sampleAccess = {kind: 'unexpected'};
  await sampleShell.confirmSampleAccess();
  assert.equal(calls.length, countBeforeInvalidAction, 'unknown actions must not fall through to deletion');
  const oldConfirm = global.confirm;
  global.confirm = () => true;
  sampleShell.loadSamples = async () => {};
  await sampleShell.clearSamples();
  assert.equal(calls.length, countBeforeInvalidAction, 'clear waits for the per-request password');
  sampleShell.samplePassword = 'clear-password';
  await sampleShell.confirmSampleAccess();
  assert.deepEqual(calls.at(-1), ['DELETE', '/samples?keep_pinned=true', {password: 'clear-password'}]);
  assert.equal(sampleShell.samplePassword, '');
  global.confirm = oldConfirm;
  let releaseBody;
  sampleShell.api = async () => new Promise(resolve => {releaseBody = resolve;});
  sampleShell.openSample(44); sampleShell.samplePassword = 'one-use-password';
  const viewing = sampleShell.confirmSampleAccess();
  sampleShell.reset();
  releaseBody({id: 44, in_body: 'late-private-body'});
  await viewing;
  assert.equal(sampleShell.sample, null, 'a late authorized response must not repopulate sample data after logout');
  console.log('manual execution and safe sample draft contracts passed');
})().catch(error => {console.error(error);process.exitCode=1;});
